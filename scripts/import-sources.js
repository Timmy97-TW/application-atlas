#!/usr/bin/env node
// Collect the "## Sources" table of every research note into
// site/data/sources.js. Global id = <note code>-<local id>, e.g. A1-S3.
// The note code comes from front-matter `code:` or from CODES below.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const rdir = path.join(root, 'research');

const CODES = {
  'common-app-first-year-anatomy': ['A1', { zh: 'A1 Common App 申請表結構', en: 'A1 Common App first-year anatomy' }],
  'other-application-systems': ['A2', { zh: 'A2 其他申請系統', en: 'A2 Other application systems' }],
  'cycle-2026-27-calendar-part1': ['A3a', { zh: 'A3 時程（1–15 校）', en: 'A3 Calendar (schools 1–15)' }],
  'cycle-2026-27-calendar-part2': ['A3b', { zh: 'A3 時程（16–30 校）', en: 'A3 Calendar (schools 16–30)' }],
  'international-applicant-specifics': ['A4', { zh: 'A4 國際申請者', en: 'A4 International applicants' }],
  'school-roster-part1': ['A5a', { zh: 'A5 逐校資料（1–15）', en: 'A5 School roster (1–15)' }],
  'school-roster-part2': ['A5b', { zh: 'A5 逐校資料（16–30）', en: 'A5 School roster (16–30)' }],
  'portal-taxonomy': ['B1', { zh: 'B1 上傳入口分類', en: 'B1 Portal taxonomy' }],
  'supplementary-materials-matrix': ['B2', { zh: 'B2／B4 補充材料矩陣', en: 'B2/B4 Supplementary-materials matrix' }],
  'engineering-portfolios': ['B3', { zh: 'B3 工程作品集', en: 'B3 Engineering portfolios' }],
  'reader-side-reality': ['B5', { zh: 'B5 審查端（官方說法）', en: 'B5 Reader side, official statements' }],
  'outside-record-frameworks': ['C1', { zh: 'C1–C3 校外紀錄框架', en: 'C1–C3 Outside-record frameworks' }],
  'ai-policy': ['C4', { zh: 'C4 AI 政策', en: 'C4 AI policy' }],
  'ucas-system-and-tests': ['F1', { zh: 'F1／F2 UCAS 與入學考試', en: 'F1/F2 UCAS and admissions tests' }],
  'uk-universities-engineering-biology': ['F3', { zh: 'F3 英國十校', en: 'F3 Ten UK universities' }],
  'us-schools-31-50-part1': ['G1', { zh: 'G 美國 31–40 校', en: 'G US schools 31–40' }],
  'cds-numbers': ['B6', { zh: 'B5 補充：Common Data Set 數字', en: 'B5 supplement: Common Data Set numbers' }],
  'admissions-own-voice': ['B7', { zh: 'B5 補充：招生辦公室自己的說法', en: 'B5 supplement: admissions offices in their own words' }],
  'counselor-side-and-taiwan-logistics': ['A6', { zh: 'A4 補充：輔導老師端與台灣考試實務', en: 'A4 supplement: counselor side and Taiwan logistics' }],
  'blocked-pages-browser-pass': ['LEAD', { zh: '待查線索（未讀到頁面本身）', en: 'Leads only (pages not read)' }],
  'michigan-addendum':['MI', { zh: 'Michigan 補充（網頁拒絕自動存取）', en: 'Michigan addendum (pages refuse automated access)' }],
  'us-schools-31-50-part2':['G2', { zh: 'G 美國 41–50 校', en: 'G US schools 41–50' }]
};

function cells(line) {
  return line.trim().replace(/^\||\|$/g, '').split('|').map(s => s.trim());
}

const out = {};
const groups = {};
const report = [];
for (const f of fs.readdirSync(rdir).filter(f => f.endsWith('.md')).sort()) {
  const text = fs.readFileSync(path.join(rdir, f), 'utf8');
  const topic = f.replace(/^\d{4}-\d{2}-\d{2}_/, '').replace(/_v\d+\.md$/, '');
  const fmCode = (text.match(/^code:\s*(\S+)/m) || [])[1];
  const [code, label] = CODES[topic] || [fmCode || topic, { zh: topic, en: topic }];
  groups[code] = label;
  // "## Sources" section, or a table directly under a front-matter `sources:` line
  const m = text.match(/^##+\s*Sources[^\n]*\n([\s\S]*?)(?=^##\s|(?![\s\S]))/m) ||
    text.match(/^sources:\s*\n((?:\s*\|[^\n]*\n)+)/m);
  if (!m) { report.push(`${f}: no Sources section`); continue; }
  const lines = m[1].split('\n').filter(l => /^\s*\|/.test(l));
  if (lines.length < 2) { report.push(`${f}: empty Sources table`); continue; }
  const head = cells(lines[0]).map(h => h.toLowerCase());
  const col = name => head.findIndex(h => h.includes(name));
  const iId = col('id'), iUrl = col('url'), iDate = col('access'), iCls = col('class'), iSup = col('support');
  let n = 0;
  for (const l of lines.slice(1)) {
    if (/^\s*\|\s*:?-{2,}/.test(l)) continue;
    const c = cells(l);
    const id = (c[iId] || '').replace(/[\[\]*`]/g, '');
    const urlRaw = c[iUrl] || '';
    const url = (urlRaw.match(/https?:\/\/[^\s)<>\]]+/) || [])[0];
    if (!id || !url) continue;
    const cls = /official/i.test(c[iCls] || '') ? 'official' : 'secondary';
    const accessed = ((c[iDate] || '').match(/\d{4}-\d{2}-\d{2}/) || ['2026-11-07'])[0];
    const supports = (c[iSup] || '').replace(/\s+/g, ' ').slice(0, 300);
    out[`${code}-${id}`] = { url, accessed, cls, group: code, title: { zh: supports || url, en: supports || url }, note: { zh: '研究筆記：' + f, en: 'Research note: ' + f } };
    n++;
  }
  report.push(`${f}: ${n} sources as ${code}-*`);
}
// Sources added by hand for site-level statements live in sources-extra.json.
const extra = path.join(root, 'research', 'sources-extra.json');
if (fs.existsSync(extra)) Object.assign(out, JSON.parse(fs.readFileSync(extra, 'utf8')));

const js = '// Generated by scripts/import-sources.js from research/*.md. Do not edit by hand.\n' +
  'window.ATLAS = window.ATLAS || {};\nwindow.ATLAS.sourceGroups = ' + JSON.stringify(groups, null, 1) +
  ';\nwindow.ATLAS.sources = ' + JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(path.join(root, 'site/data/sources.js'), js);
console.log(report.join('\n'));
console.log('total', Object.keys(out).length);
