#!/usr/bin/env node
// Regenerate site/data/log.js (from briefs/ and QUESTIONS.md) and
// site/data/status.js (BACKLOG progress, matrix cells by source class,
// oldest access date, open questions). No other build step exists.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');
const rd = p => fs.readFileSync(path.join(root, p), 'utf8');

function frontMatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const fm = {};
  if (m) for (const line of m[1].split('\n')) {
    const k = line.match(/^(\w+):\s*(.*)$/);
    if (k) fm[k[1]] = k[2].replace(/^["']|["']$/g, '');
  }
  return fm;
}
function sectionList(text, heading) {
  const re = new RegExp('^##+\\s*' + heading + '[^\\n]*\\n([\\s\\S]*?)(?=^##\\s|$(?![\\s\\S]))', 'mi');
  const m = text.match(re);
  if (!m) return [];
  return m[1].split('\n').filter(l => /^\s*[-*]\s+/.test(l)).map(l => l.replace(/^\s*[-*]\s+/, '').trim());
}

// briefs → log entries
const briefs = fs.readdirSync(path.join(root, 'briefs')).filter(f => f.endsWith('.md')).sort().reverse();
const entries = briefs.map(f => {
  const t = rd('briefs/' + f);
  const fm = frontMatter(t);
  return {
    file: 'briefs/' + f,
    date: fm.date || f.slice(0, 10),
    unit: fm.unit || '',
    status: fm.status || '',
    title_zh: fm.title_zh || '',
    title_en: fm.title_en || fm.title || '',
    done: sectionList(t, 'Done').slice(0, 30),
    notDone: sectionList(t, 'Not done').slice(0, 30),
    by: f.includes('_timmy') ? 'maintainer' : 'run'
  };
});

// QUESTIONS.md
const qtext = rd('QUESTIONS.md');
const questions = [];
const qre = /^(Q\d{3}) · (\S+) · ([^·]+?) · (open|answered|applied)([^\n]*)\n([\s\S]*?)(?=^Q\d{3} · |(?![\s\S]))/gm;
for (const m of qtext.matchAll(qre)) {
  const body = m[6].trim();
  const a = body.match(/^A:\s*([\s\S]*)$/m);
  questions.push({
    id: m[1], date: m[2], unit: m[3].trim(), state: m[4], stateNote: m[5].trim(),
    q: body.replace(/^A:[\s\S]*$/m, '').trim(), a: a ? a[1].trim() : ''
  });
}

// BACKLOG progress
const bl = rd('BACKLOG.md');
const units = [...bl.matchAll(/^- \[( |x)\] ([A-Z]\d+)\b/gm)].map(m => ({ id: m[2], done: m[1] === 'x' }));

// matrix cells by source class + oldest access date, from data files
const ctx = { window: {} };
vm.createContext(ctx);
const dd = path.join(root, 'site/data');
for (const f of fs.readdirSync(dd).filter(f => f.endsWith('.js') && !['log.js', 'status.js'].includes(f)).sort()) {
  vm.runInContext(fs.readFileSync(path.join(dd, f), 'utf8'), ctx, { filename: f });
}
const A = ctx.window.ATLAS || {};
const sources = A.sources || {};
const cells = { official: 0, secondary: 0, notStated: 0 };
for (const row of (A.matrix && A.matrix.rows) || []) {
  for (const c of row.cells || []) {
    if (!c || c.state === 'not-stated') { cells.notStated++; continue; }
    const cls = (c.src || []).map(s => sources[s] && sources[s].cls);
    if (cls.includes('official')) cells.official++; else if (cls.length) cells.secondary++; else cells.notStated++;
  }
}
const dates = Object.values(sources).map(s => s.accessed).filter(Boolean).sort();
const nSrc = Object.values(sources);

const status = {
  generated: new Date().toISOString().slice(0, 10),
  units: { done: units.filter(u => u.done).length, total: units.length },
  sections: Object.fromEntries([...new Set(units.map(u => u.id[0]))].map(s => [s, {
    done: units.filter(u => u.id[0] === s && u.done).length, total: units.filter(u => u.id[0] === s).length
  }])),
  cells,
  sources: { total: nSrc.length, official: nSrc.filter(s => s.cls === 'official').length, secondary: nSrc.filter(s => s.cls === 'secondary').length },
  oldestAccess: dates[0] || null,
  openQuestions: questions.filter(q => q.state === 'open').length,
  notes: fs.readdirSync(path.join(root, 'research')).filter(f => f.endsWith('.md')).length
};

const hdr = '// Generated by scripts/build-log.js. Do not edit by hand.\n';
fs.writeFileSync(path.join(dd, 'log.js'), hdr + 'window.ATLAS = window.ATLAS || {};\nwindow.ATLAS.log = ' + JSON.stringify({ entries, questions }, null, 1) + ';\n');
fs.writeFileSync(path.join(dd, 'status.js'), hdr + 'window.ATLAS = window.ATLAS || {};\nwindow.ATLAS.status = ' + JSON.stringify(status, null, 1) + ';\n');
console.log(`log: ${entries.length} briefs, ${questions.length} questions; status: ${status.units.done}/${status.units.total} units, ${status.sources.total} sources`);
